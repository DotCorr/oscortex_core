/* Weak so OSGFX_SKIA=0 still links. osxui.c is the strong symbol. */
__attribute__((weak)) void osxui_hex_fb(uint64_t fb, uint64_t pitch,
                                        uint64_t wh, uint64_t xy,
                                        uint64_t value, uint64_t nrgb) {
  char buf[8];
  int n;
  int i;

  n = (int)(nrgb >> 32);
  if (n < 1) {
    return;
  }
  if (n > 8) {
    n = 8;
  }
  i = n;
  while (i > 0) {
    i = i - 1;
    buf[i] = "0123456789ABCDEF"[value & 15u];
    value = value >> 4;
  }
  osxui_label_fb(fb, pitch, wh, xy, (uint64_t)(uintptr_t)buf, nrgb);
}

