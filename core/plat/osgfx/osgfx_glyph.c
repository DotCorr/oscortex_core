/* Token: chrome labels are soft-AA, not put_px stamps. */
const char osgfx_glyph_aa_door[] = "osgfx-glyph-aa";

static int glyph_bit(const uint8_t *rows, int c, int r) {
  if (rows == 0 || c < 0 || r < 0 || c >= OSGFX_GLYPH_W || r >= OSGFX_GLYPH_H) {
    return 0;
  }
  return (rows[r] >> (7 - c)) & 1;
}

/* Soft coverage — edge fringe blends; interior stays opaque. */
static uint8_t glyph_cov(const uint8_t *rows, int c, int r) {
  int n;
  int cov;

  if (glyph_bit(rows, c, r) != 0) {
    return 255;
  }
  n = 0;
  n = n + glyph_bit(rows, c - 1, r);
  n = n + glyph_bit(rows, c + 1, r);
  n = n + glyph_bit(rows, c, r - 1);
  n = n + glyph_bit(rows, c, r + 1);
  n = n + glyph_bit(rows, c - 1, r - 1);
  n = n + glyph_bit(rows, c + 1, r - 1);
  n = n + glyph_bit(rows, c - 1, r + 1);
  n = n + glyph_bit(rows, c + 1, r + 1);
  if (n <= 0) {
    return 0;
  }
  /* Stronger fringe (~100..255) so labels read painted, not stamped. */
  cov = 70 + n * 32;
  if (cov > 255) {
    cov = 255;
  }
  return (uint8_t)cov;
}

static void blend_store(uint32_t *px, int pitch, int w, int h, int x, int y,
                        uint32_t rgb, uint8_t cov) {
  uint8_t *row;
  uint32_t dst;
  unsigned a;
  unsigned ia;
  unsigned sr;
  unsigned sg;
  unsigned sb;
  unsigned dr;
  unsigned dg;
  unsigned db;

  if (px == 0 || pitch < 4 || w < 1 || h < 1 || cov == 0) {
    return;
  }
  if (x < 0 || y < 0 || x >= w || y >= h) {
    return;
  }
  row = (uint8_t *)px + (unsigned)y * (unsigned)pitch;
  if (cov >= 250) {
    *(uint32_t *)(row + (unsigned)x * 4u) = rgb & 0x00FFFFFFu;
    return;
  }
  dst = *(uint32_t *)(row + (unsigned)x * 4u);
  a = (unsigned)cov;
  ia = 255u - a;
  sr = (rgb >> 16) & 0xffu;
  sg = (rgb >> 8) & 0xffu;
  sb = rgb & 0xffu;
  dr = (dst >> 16) & 0xffu;
  dg = (dst >> 8) & 0xffu;
  db = dst & 0xffu;
  dr = (sr * a + dr * ia) / 255u;
  dg = (sg * a + dg * ia) / 255u;
  db = (sb * a + db * ia) / 255u;
  *(uint32_t *)(row + (unsigned)x * 4u) =
      ((dr & 0xffu) << 16) | ((dg & 0xffu) << 8) | (db & 0xffu);
}

/* Weak so osgfx_skia.cpp can supply SkCanvas AA silhouette paint. */
__attribute__((weak)) void osgfx_fill_glyph(OsGfx *g, int x, int y,
                                            const uint8_t *rows, uint32_t rgb) {
  int r;
  int c;
  uint8_t cov;

  if (g == 0 || rows == 0) {
    return;
  }
  if (osgfx_glyph_aa_door[0] == 0) {
    return;
  }
  r = 0;
  while (r < OSGFX_GLYPH_H) {
    c = 0;
    while (c < OSGFX_GLYPH_W) {
      cov = glyph_cov(rows, c, r);
      if (cov > 0) {
        osgfx_blend_px(g, x + c, y + r, rgb, cov);
      }
      c = c + 1;
    }
    r = r + 1;
  }
}

__attribute__((weak)) void osgfx_blend_px(OsGfx *g, int x, int y, uint32_t rgb,
                                          uint8_t cov) {
  if (cov >= 128) {
    osgfx_fill_rect(g, x, y, 1, 1, rgb);
  }
  (void)cov;
}

static void fill_glyph_store(uint32_t *px, int pitch, int w, int h, int x, int y,
                             const uint8_t *rows, uint32_t rgb) {
  int r;
  int c;
  uint8_t cov;

  if (rows == 0) {
    return;
  }
  r = 0;
  while (r < OSGFX_GLYPH_H) {
    c = 0;
    while (c < OSGFX_GLYPH_W) {
      cov = glyph_cov(rows, c, r);
      if (cov > 0) {
        blend_store(px, pitch, w, h, x + c, y + r, rgb, cov);
      }
      c = c + 1;
    }
    r = r + 1;
  }
}

void osxui_label_fb(uint64_t fb, uint64_t pitch, uint64_t wh, uint64_t xy,
                    uint64_t text, uint64_t nrgb) {
  uint32_t *px;
  int w;
  int h;
  int x;
  int y;
  int n;
  uint32_t rgb;
  const char *s;
  int i;

  px = (uint32_t *)(uintptr_t)fb;
  w = (int)(wh >> 32);
  h = (int)wh;
  x = (int)(xy >> 32);
  y = (int)xy;
  n = (int)(nrgb >> 32);
  rgb = (uint32_t)nrgb;
  s = (const char *)(uintptr_t)text;
  if (px == 0 || s == 0 || n < 1 || w < 8 || h < 8) {
    return;
  }
  i = 0;
  while (i < n) {
    unsigned char c = (unsigned char)s[i];
    if (c == 0) {
      break;
    }
    if (c == (unsigned char)' ') {
      break;
    }
    fill_glyph_store(px, (int)pitch, w, h, x + i * OSGFX_GLYPH_W, y,
                     osgfx_glyph_rows((int)c), rgb);
    i = i + 1;
  }
}

void osxui_icon_fb(uint64_t fb, uint64_t pitch, uint64_t wh, uint64_t xy,
                   uint64_t rgb) {
  uint32_t *px;
  int w;
  int h;
  int x;
  int y;

  px = (uint32_t *)(uintptr_t)fb;
  w = (int)(wh >> 32);
  h = (int)wh;
  x = (int)(xy >> 32);
  y = (int)xy;
  if (px == 0 || w < OSGFX_ICON_W || h < OSGFX_ICON_H) {
    return;
  }
  fill_glyph_store(px, (int)pitch, w, h, x, y, osgfx_icon_rows(),
                   (uint32_t)rgb);
}

