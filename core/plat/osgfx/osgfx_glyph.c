const uint8_t *osgfx_glyph_rows(int ch) {
  if (ch < 0x20 || ch > 0x7E) {
    return osgfx_font8x16 + 95 * 16;
  }
  return osgfx_font8x16 + ((ch - 0x20) * 16);
}

